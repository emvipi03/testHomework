test('supports choose-then-place controls and clearing saved progress', async ({ page }) => {
  await openLesson(page)
  await page.getByLabel('Inventor name').fill('Casey')
  await page.getByRole('button', { name: /Start mission/ }).click()
  await page.getByRole('button', { name: /I’m ready/ }).click()
  const fill = page.locator('[data-question="q6"]')
  await fill.locator('.block-bank button').first().click()
  await expect(fill.getByText('Tap to place the selected block')).toBeVisible()
  await fill.getByRole('button', { name: 'Missing block position' }).click()
  await expect(fill.locator('.drop-zone svg')).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Clear progress' }).click()
  await expect(page.getByLabel('Inventor name')).toHaveValue('')
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!).answers, storageKey)).toEqual({})
})

test('loads the official MakeCode iframe or exposes the network fallback', async ({ page }) => {
  await openLesson(page)
  await page.getByLabel('Inventor name').fill('Drew')
  await page.getByRole('button', { name: /Start mission/ }).click()
  await page.getByRole('button', { name: /I’m ready/ }).click()
  await page.getByRole('button', { name: /Enter the coding lab/ }).click()
  await expect(page.getByTitle('Microsoft MakeCode editor for micro:bit')).toBeVisible()
  const makeCodeStatus = page.getByText(/MakeCode connected|No response from MakeCode/)
  await expect(makeCodeStatus).toBeVisible({ timeout: 12_000 })
  console.log(`MAKECODE_STATUS=${await makeCodeStatus.innerText()}`)
  await expect(page.getByRole('link', { name: /Open MakeCode in a new tab/ })).toHaveAttribute('target', '_blank')
})

test.describe('tablet', () => {
  test.use({ viewport: { width: 820, height: 1180 } })
  test('has no horizontal overflow and touch-sized controls', async ({ page }) => {
    await expect(page.getByRole('heading', { name: 'Pick your next challenge' })).toBeVisible()
    await openLesson(page)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
    expect(overflow).toBe(false)
    expect((await page.getByRole('button', { name: /Start mission/ }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
  })
})
